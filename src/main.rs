use clap::{Parser, Subcommand};
use colored::*;
use std::fs;
use std::path::PathBuf;

use aod_lint::models::diagnostics::Severity;
use aod_lint::models::manifest::AodManifest;
use aod_lint::models::rubric::Section8Rubric;
use aod_lint::passes::digest::AodDigestPass;
use aod_lint::passes::labels::{check_labels, LabelHygieneOptions};
use aod_lint::passes::latex::LatexPass;
use aod_lint::passes::slice::AodSlicePass;
use aod_lint::passes::typst_ast::TypstAstPass;

#[derive(Parser)]
#[command(name = "aod-lint")]
#[command(about = "Static source diagnostics for AOD LaTeX and Typst manuscripts")]
struct Cli {
    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand)]
enum Commands {
    /// Check literal labels in one document and its supported includes.
    Labels {
        entry: PathBuf,
        #[arg(
            long,
            help = "JSON list of actual external label names, including import prefixes"
        )]
        external_labels: Option<PathBuf>,
        #[arg(
            long,
            help = "Literal prefix added by this document's Main-reference wrappers"
        )]
        main_reference_prefix: Option<String>,
        #[arg(
            long,
            help = "JSON list of repository-relative paths for advisory name checks"
        )]
        paths: Option<PathBuf>,
        #[arg(
            long,
            help = "Disable advisory project-name warnings; keep label/reference checks"
        )]
        no_name_warnings: bool,
        #[arg(long)]
        json: bool,
    },
    Check {
        file: PathBuf,
        #[arg(
            long,
            help = "Treat lexical premise-review candidates as errors; does not prove a semantic violation"
        )]
        strict: bool,
        #[arg(long, help = "Emit machine-readable JSON for multi-agent ingestion")]
        json: bool,
    },
    Digest {
        #[arg(
            default_value = ".",
            help = "Root directory or entry .typ file of the Typst treatise"
        )]
        root: PathBuf,
        #[arg(short, long, help = "Write manifest JSON to file instead of stdout")]
        output: Option<PathBuf>,
        #[arg(
            long,
            help = "Baseline aod-manifest.json to enforce frozen main SHA-256 guard"
        )]
        baseline: Option<PathBuf>,
        #[arg(
            long,
            help = "Explicitly freeze Main and Appendix hashes in the emitted manifest"
        )]
        freeze_main: bool,
        #[arg(long, help = "Emit machine-readable JSON")]
        json: bool,
    },
    Slice {
        #[arg(
            short,
            long,
            help = "Path to aod-manifest.json generated by aod-lint digest"
        )]
        manifest: PathBuf,
        #[arg(
            short,
            long,
            help = "Path to unified diff file (e.g., from gh pr diff)"
        )]
        diff: Option<PathBuf>,
        #[arg(long, num_args = 1.., help = "Explicit list of touched relative file paths")]
        files: Vec<String>,
        #[arg(
            long,
            default_value_t = 2,
            help = "Reachability hop radius in the D.E.C./reference graph"
        )]
        hops: usize,
        #[arg(long, help = "Emit machine-readable JSON ContextBundle")]
        json: bool,
    },
}

fn main() {
    let cli = Cli::parse();

    match cli.command {
        Commands::Labels {
            entry,
            external_labels,
            main_reference_prefix,
            paths,
            no_name_warnings,
            json,
        } => {
            let load_names = |path: &Option<PathBuf>| -> Result<(Vec<String>, Option<serde_json::Value>), String> {
                if let Some(path) = path {
                    use sha2::{Digest, Sha256};
                    let path = fs::canonicalize(path).map_err(|e| format!("{}: {}", path.display(), e))?;
                    let bytes = fs::read(&path).map_err(|e| format!("{}: {}", path.display(), e))?;
                    let names: Vec<String> = serde_json::from_slice(&bytes)
                        .map_err(|e| format!("{} must contain a JSON list of strings: {}", path.display(), e))?;
                    if names.iter().any(|s| s.trim().is_empty()) { return Err("Context names must be nonempty.".into()); }
                    let binding = serde_json::json!({"path": path, "sha256": format!("{:x}", Sha256::digest(&bytes))});
                    Ok((names, Some(binding)))
                } else { Ok((Vec::new(), None)) }
            };
            let result = (|| {
                let (external_names, external_input) = load_names(&external_labels)?;
                let (path_names, paths_input) = load_names(&paths)?;
                let options = LabelHygieneOptions {
                    external_labels: external_names.into_iter().collect(),
                    main_reference_prefix,
                    additional_paths: path_names,
                    check_names: !no_name_warnings,
                };
                Ok::<_, String>((check_labels(&entry, options)?, external_input, paths_input))
            })();
            let (report, external_input, paths_input) = match result {
                Ok(report) => report,
                Err(message) => {
                    if json {
                        println!(
                            "{}",
                            serde_json::json!({"status": "INPUT_ERROR", "message": message})
                        );
                    } else {
                        eprintln!("Label hygiene input error: {}", message);
                    }
                    std::process::exit(1);
                }
            };
            if json {
                let mut output = serde_json::to_value(&report).unwrap();
                for (key, binding) in [
                    ("external_labels_input", external_input),
                    ("additional_paths_input", paths_input),
                ] {
                    if let Some(binding) = binding {
                        output[key] = binding;
                    }
                }
                println!("{}", serde_json::to_string_pretty(&output).unwrap());
            } else {
                println!(
                    "Label hygiene: {} ({} source files, {} literal labels)",
                    report.status,
                    report.files.len(),
                    report.labels.len()
                );
                for d in &report.diagnostics {
                    println!(
                        "{:?} [{}] {}:{}:{} — {}",
                        d.severity, d.kind, d.file, d.line, d.column, d.message
                    );
                    for at in &d.related {
                        println!("  also defined at {}:{}:{}", at.file, at.line, at.column);
                    }
                }
                for gap in &report.coverage_gaps {
                    println!(
                        "Partial coverage: {}:{} — {}",
                        gap.file, gap.line, gap.reason
                    );
                }
                println!("Read-only literal checks; no compilation or scientific certification.");
            }
            std::process::exit(report.exit_code());
        }
        Commands::Check { file, strict, json } => {
            let path_str = file.to_string_lossy();
            let content = match fs::read_to_string(&file) {
                Ok(c) => c,
                Err(err) => {
                    eprintln!(
                        "{} Failed to read {}: {}",
                        "error:".red().bold(),
                        path_str,
                        err
                    );
                    std::process::exit(1);
                }
            };

            let diagnostics = if file
                .extension()
                .and_then(|e| e.to_str())
                .map(|e| e.eq_ignore_ascii_case("tex"))
                .unwrap_or(false)
            {
                LatexPass::new(&path_str, &content, strict).run()
            } else {
                TypstAstPass::new(&path_str, &content, strict).run()
            };

            let rubric = Section8Rubric::new();

            let candidate_count = diagnostics
                .iter()
                .filter(|d| d.dependency_candidate)
                .count();

            if json {
                let output = serde_json::json!({
                    "schema_version": "2.0",
                    "target": path_str,
                    "strict_mode": strict,
                    "coverage": "static_source",
                    "semantic_review": "not_checked",
                    "rubric": rubric,
                    "candidate_dependencies": candidate_count,
                    "hoisting": "not_performed",
                    "diagnostics": diagnostics,
                });
                println!("{}", serde_json::to_string_pretty(&output).unwrap());
            } else {
                println!(
                    "{}",
                    "======================================================================".cyan()
                );
                println!("                  AOD-LINT STATIC SOURCE REPORT");
                println!(
                    "{}",
                    "======================================================================".cyan()
                );
                println!("Target: {}", path_str.bold());
                println!(
                    "Mode:   {}",
                    if strict {
                        "STRICT LEXICAL DIAGNOSTICS"
                    } else {
                        "ADVISORY LEXICAL DIAGNOSTICS"
                    }
                );
                println!(
                    "Dependency review candidates: {} (no hoisting performed)",
                    candidate_count
                );
                println!("AF semantic review: not checked (all eight rubric questions).");
                println!(
                    "{}",
                    "----------------------------------------------------------------------".cyan()
                );

                if diagnostics.is_empty() {
                    println!(
                        "{}",
                        "No lexical diagnostics found; semantic validity is not assessed."
                            .green()
                            .bold()
                    );
                } else {
                    for d in &diagnostics {
                        let icon = match d.severity {
                            Severity::Fatal | Severity::Error => "❌".red(),
                            Severity::Warning => "⚠️ ".yellow(),
                            Severity::Info => "💡".blue(),
                        };
                        println!("{} [{:?}] {}", icon, d.severity, d.rule.as_str().bold());
                        println!("   --> {}:{}:{}", d.file, d.line, d.column);
                        println!("   | {}", d.message);
                        if let Some(fix) = &d.suggested_fix {
                            println!("   = suggestion: {}", fix.green());
                        }
                        println!();
                    }
                }
                println!(
                    "{}",
                    "======================================================================".cyan()
                );
            }

            let has_fatal = diagnostics
                .iter()
                .any(|d| d.severity == Severity::Fatal || d.severity == Severity::Error);
            if has_fatal {
                std::process::exit(1);
            }
        }
        Commands::Digest {
            root,
            output,
            baseline,
            freeze_main,
            json,
        } => {
            let pass = AodDigestPass::new(&root).with_frozen_main(freeze_main);
            let mut manifest = match pass.run() {
                Ok(m) => m,
                Err(err) => {
                    eprintln!("{} {}", "error:".red().bold(), err);
                    std::process::exit(1);
                }
            };

            let mut frozen_violations = Vec::new();
            if let Some(base_path) = baseline {
                let base_str = match fs::read_to_string(&base_path) {
                    Ok(s) => s,
                    Err(err) => {
                        eprintln!(
                            "{} Failed to read baseline {}: {}",
                            "error:".red().bold(),
                            base_path.display(),
                            err
                        );
                        std::process::exit(1);
                    }
                };
                let base_manifest: AodManifest = match serde_json::from_str(&base_str) {
                    Ok(m) => m,
                    Err(err) => {
                        eprintln!("{} Invalid baseline JSON: {}", "error:".red().bold(), err);
                        std::process::exit(1);
                    }
                };
                frozen_violations =
                    AodDigestPass::verify_frozen_baseline(&base_manifest, &manifest);
            }

            manifest.frozen_baseline_violations = frozen_violations.clone();

            let manifest_json = serde_json::to_string_pretty(&manifest).unwrap();
            if let Some(out_path) = output {
                if let Err(err) = fs::write(&out_path, &manifest_json) {
                    eprintln!(
                        "{} Failed to write {}: {}",
                        "error:".red().bold(),
                        out_path.display(),
                        err
                    );
                    std::process::exit(1);
                }
            } else if json {
                println!("{}", manifest_json);
            } else {
                println!(
                    "AOD-DIGEST: {} source file(s), {} edge(s), {} firewall violation(s), {} include cycle(s)",
                    manifest.files.len(),
                    manifest.edges.len(),
                    manifest.firewall_violations.len(),
                    manifest.include_cycles.len()
                );
                for v in &manifest.firewall_violations {
                    println!("  ❌ {}:{} — {}", v.origin_file, v.line, v.message);
                }
                for v in &frozen_violations {
                    println!("  ❌ FROZEN MAIN GUARD: {}", v);
                }
                for gap in &manifest.coverage_gaps {
                    println!("  Partial coverage: {}", gap);
                }
            }

            if !manifest.firewall_violations.is_empty()
                || !manifest.include_cycles.is_empty()
                || !frozen_violations.is_empty()
            {
                std::process::exit(1);
            }
            if !manifest.coverage_gaps.is_empty() {
                std::process::exit(2);
            }
        }
        Commands::Slice {
            manifest,
            diff,
            files,
            hops,
            json,
        } => {
            let manifest_str = match fs::read_to_string(&manifest) {
                Ok(s) => s,
                Err(err) => {
                    eprintln!(
                        "{} Failed to read manifest {}: {}",
                        "error:".red().bold(),
                        manifest.display(),
                        err
                    );
                    std::process::exit(1);
                }
            };
            let parsed_manifest: AodManifest = match serde_json::from_str(&manifest_str) {
                Ok(m) => m,
                Err(err) => {
                    eprintln!("{} Invalid manifest JSON: {}", "error:".red().bold(), err);
                    std::process::exit(1);
                }
            };

            let pass = AodSlicePass::new(&parsed_manifest, hops);
            let bundle = if let Some(diff_path) = diff {
                let diff_text = match fs::read_to_string(&diff_path) {
                    Ok(s) => s,
                    Err(err) => {
                        eprintln!(
                            "{} Failed to read diff {}: {}",
                            "error:".red().bold(),
                            diff_path.display(),
                            err
                        );
                        std::process::exit(1);
                    }
                };
                pass.run_from_diff(&diff_text)
            } else if !files.is_empty() {
                pass.run_from_files(files)
            } else {
                eprintln!(
                    "{} Provide either --diff <file> or --files <path>...",
                    "error:".red().bold()
                );
                std::process::exit(1);
            };

            if json {
                println!("{}", serde_json::to_string_pretty(&bundle).unwrap());
            } else {
                println!(
                    "AOD-SLICE (hops={}): {} touched, {} impacted file(s), {} frozen violation(s)",
                    bundle.hops,
                    bundle.touched_files.len(),
                    bundle.impacted_files.len(),
                    bundle.frozen_main_violations.len()
                );
                for v in &bundle.frozen_main_violations {
                    println!("  ❌ {}", v);
                }
                for ex in &bundle.excerpts {
                    println!(
                        "  - {} ({:?}, lines {}-{}, {})",
                        ex.file, ex.tier, ex.start_line, ex.end_line, ex.reason
                    );
                }
            }

            if !bundle.frozen_main_violations.is_empty() {
                std::process::exit(1);
            }
        }
    }
}
