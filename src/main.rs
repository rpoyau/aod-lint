use clap::{Parser, Subcommand};
use colored::*;
use std::fs;
use std::path::PathBuf;

use aod_lint::models::diagnostics::Severity;
use aod_lint::models::manifest::AodManifest;
use aod_lint::models::rubric::Section8Rubric;
use aod_lint::passes::digest::AodDigestPass;
use aod_lint::passes::slice::AodSlicePass;
use aod_lint::passes::typst_ast::TypstAstPass;

#[derive(Parser)]
#[command(name = "aod-lint")]
#[command(about = "Axiomatic Fundamentalism & D.E.C. Compiler/Linter for Typst")]
struct Cli {
    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand)]
enum Commands {
    Check {
        file: PathBuf,
        #[arg(long, help = "Enforce strict internal AOD mode (no midstream hoisting allowed)")]
        strict: bool,
        #[arg(long, help = "Emit machine-readable JSON for multi-agent ingestion")]
        json: bool,
    },
    Digest {
        #[arg(default_value = ".", help = "Root directory or entry .typ file of the Typst treatise")]
        root: PathBuf,
        #[arg(short, long, help = "Write manifest JSON to file instead of stdout")]
        output: Option<PathBuf>,
        #[arg(long, help = "Baseline aod-manifest.json to enforce frozen main SHA-256 guard")]
        baseline: Option<PathBuf>,
        #[arg(long, help = "Emit machine-readable JSON")]
        json: bool,
    },
    Slice {
        #[arg(short, long, help = "Path to aod-manifest.json generated by aod-lint digest")]
        manifest: PathBuf,
        #[arg(short, long, help = "Path to unified diff file (e.g., from gh pr diff)")]
        diff: Option<PathBuf>,
        #[arg(long, num_args = 1.., help = "Explicit list of touched relative file paths")]
        files: Vec<String>,
        #[arg(long, default_value_t = 2, help = "Reachability hop radius in the D.E.C./reference graph")]
        hops: usize,
        #[arg(long, help = "Emit machine-readable JSON ContextBundle")]
        json: bool,
    },
}

fn main() {
    let cli = Cli::parse();

    match cli.command {
        Commands::Check { file, strict, json } => {
            let path_str = file.to_string_lossy();
            let content = match fs::read_to_string(&file) {
                Ok(c) => c,
                Err(err) => {
                    eprintln!("{} Failed to read {}: {}", "error:".red().bold(), path_str, err);
                    std::process::exit(1);
                }
            };

            let pass = TypstAstPass::new(&path_str, &content, strict);
            let diagnostics = pass.run();

            let mut rubric = Section8Rubric::new();
            rubric.apply_diagnostics(&diagnostics);

            let hoisted_count = diagnostics.iter().filter(|d| d.hoisted).count();

            if json {
                let output = serde_json::json!({
                    "target": path_str,
                    "strict_mode": strict,
                    "converged": rubric.is_converged(),
                    "rubric_bits": rubric.to_bitstring(),
                    "hoisted_dependencies": hoisted_count,
                    "diagnostics": diagnostics,
                });
                println!("{}", serde_json::to_string_pretty(&output).unwrap());
            } else {
                println!("{}", "======================================================================".cyan());
                println!("                  AOD-LINT AXIOMATIC REPORT (Rust Engine)");
                println!("{}", "======================================================================".cyan());
                println!("Target: {}", path_str.bold());
                println!("Mode:   {}", if strict { "STRICT (Internal AOD)" } else { "DIAGNOSTIC (Two-Pass Hoisting)" });
                println!("Hoisted Dependencies: {}", hoisted_count);
                println!(
                    "Section 8 Rubric: [{}] (Converged: {})",
                    rubric.to_bitstring().yellow(),
                    if rubric.is_converged() { "YES".green().bold() } else { "NO".red().bold() }
                );
                println!("{}", "----------------------------------------------------------------------".cyan());

                if diagnostics.is_empty() {
                    println!("{}", "✅ All checks passed. 100% AF compliant.".green().bold());
                } else {
                    for d in &diagnostics {
                        let icon = match d.severity {
                            Severity::Fatal | Severity::Error => "❌".red(),
                            Severity::Warning => "⚠️ ".yellow(),
                            Severity::Info => "💡".blue(),
                        };
                        println!("{} [{:?}] {}", icon, d.severity, d.rule.as_str().bold());
                        println!("   --> {}:{}:{}", d.file, d.line, d.column);
                        println!("   | {}", d.message);
                        if let Some(fix) = &d.suggested_fix {
                            println!("   = suggestion: {}", fix.green());
                        }
                        println!();
                    }
                }
                println!("{}", "======================================================================".cyan());
            }

            let has_fatal = diagnostics
                .iter()
                .any(|d| d.severity == Severity::Fatal || d.severity == Severity::Error);
            if has_fatal {
                std::process::exit(1);
            }
        }
        Commands::Digest {
            root,
            output,
            baseline,
            json,
        } => {
            let pass = AodDigestPass::new(&root);
            let manifest = match pass.run() {
                Ok(m) => m,
                Err(err) => {
                    eprintln!("{} {}", "error:".red().bold(), err);
                    std::process::exit(1);
                }
            };

            let mut frozen_violations = Vec::new();
            if let Some(base_path) = baseline {
                let base_str = match fs::read_to_string(&base_path) {
                    Ok(s) => s,
                    Err(err) => {
                        eprintln!(
                            "{} Failed to read baseline {}: {}",
                            "error:".red().bold(),
                            base_path.display(),
                            err
                        );
                        std::process::exit(1);
                    }
                };
                let base_manifest: AodManifest = match serde_json::from_str(&base_str) {
                    Ok(m) => m,
                    Err(err) => {
                        eprintln!("{} Invalid baseline JSON: {}", "error:".red().bold(), err);
                        std::process::exit(1);
                    }
                };
                frozen_violations = AodDigestPass::verify_frozen_baseline(&base_manifest, &manifest);
            }

            let manifest_json = serde_json::to_string_pretty(&manifest).unwrap();
            if let Some(out_path) = output {
                if let Err(err) = fs::write(&out_path, &manifest_json) {
                    eprintln!(
                        "{} Failed to write {}: {}",
                        "error:".red().bold(),
                        out_path.display(),
                        err
                    );
                    std::process::exit(1);
                }
            } else if json {
                println!("{}", manifest_json);
            } else {
                println!(
                    "AOD-DIGEST: {} Typst file(s), {} edge(s), {} firewall violation(s), {} include cycle(s)",
                    manifest.files.len(),
                    manifest.edges.len(),
                    manifest.firewall_violations.len(),
                    manifest.include_cycles.len()
                );
                for v in &manifest.firewall_violations {
                    println!("  ❌ {}:{} — {}", v.origin_file, v.line, v.message);
                }
                for v in &frozen_violations {
                    println!("  ❌ FROZEN MAIN GUARD: {}", v);
                }
            }

            if !manifest.firewall_violations.is_empty()
                || !manifest.include_cycles.is_empty()
                || !frozen_violations.is_empty()
            {
                std::process::exit(1);
            }
        }
        Commands::Slice {
            manifest,
            diff,
            files,
            hops,
            json,
        } => {
            let manifest_str = match fs::read_to_string(&manifest) {
                Ok(s) => s,
                Err(err) => {
                    eprintln!(
                        "{} Failed to read manifest {}: {}",
                        "error:".red().bold(),
                        manifest.display(),
                        err
                    );
                    std::process::exit(1);
                }
            };
            let parsed_manifest: AodManifest = match serde_json::from_str(&manifest_str) {
                Ok(m) => m,
                Err(err) => {
                    eprintln!("{} Invalid manifest JSON: {}", "error:".red().bold(), err);
                    std::process::exit(1);
                }
            };

            let pass = AodSlicePass::new(&parsed_manifest, hops);
            let bundle = if let Some(diff_path) = diff {
                let diff_text = match fs::read_to_string(&diff_path) {
                    Ok(s) => s,
                    Err(err) => {
                        eprintln!(
                            "{} Failed to read diff {}: {}",
                            "error:".red().bold(),
                            diff_path.display(),
                            err
                        );
                        std::process::exit(1);
                    }
                };
                pass.run_from_diff(&diff_text)
            } else if !files.is_empty() {
                pass.run_from_files(files)
            } else {
                eprintln!("{} Provide either --diff <file> or --files <path>...", "error:".red().bold());
                std::process::exit(1);
            };

            if json {
                println!("{}", serde_json::to_string_pretty(&bundle).unwrap());
            } else {
                println!(
                    "AOD-SLICE (hops={}): {} touched, {} impacted file(s), {} frozen violation(s)",
                    bundle.hops,
                    bundle.touched_files.len(),
                    bundle.impacted_files.len(),
                    bundle.frozen_main_violations.len()
                );
                for v in &bundle.frozen_main_violations {
                    println!("  ❌ {}", v);
                }
                for ex in &bundle.excerpts {
                    println!(
                        "  - {} ({:?}, lines {}-{}, {})",
                        ex.file, ex.tier, ex.start_line, ex.end_line, ex.reason
                    );
                }
            }

            if !bundle.frozen_main_violations.is_empty() {
                std::process::exit(1);
            }
        }
    }
}
